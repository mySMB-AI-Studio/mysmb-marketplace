import html as _html

problem = params.get("problem") or ""
summary = params.get("summary") or {}
artifact_url = ""
if not problem:
    clients = summary.get("clients") or []
    commentary = ""
    if clients:
        commentary = api.ai.generate(
            prompt=("You write the weekly accounts payable note for an Australian bookkeeping team. In 3 to 5 short "
                    "bullet points, say what needs attention this week: overdue bills, bills waiting for review or "
                    "approval, and exceptions. Name the businesses. Use only the numbers given; don't add advice."),
            input=json.dumps(summary)[:28000],
        )

    def cell(pair):
        return str(pair[0]) + " · " + bk_fmt(pair[1]) if pair[0] else "—"

    rows = []
    for c in clients:
        rows.append(
            "<tr><td>" + _html.escape(str(c.get("name") or "")) + "</td>"
            + "<td>" + (str(c["in_review"]) if c["in_review"] else "—") + "</td>"
            + "<td>" + (str(c["exceptions"]) if c["exceptions"] else "—") + "</td>"
            + "<td>" + cell(c["draft"]) + "</td><td>" + cell(c["awaiting"]) + "</td>"
            + "<td>" + cell(c["due_soon"]) + "</td><td class='od'>" + cell(c["overdue"]) + "</td>"
            + "<td>" + _html.escape(c.get("error") or "") + "</td></tr>"
        )
    bullets = "".join("<li>" + _html.escape(line.lstrip("-•* ").strip()) + "</li>"
                      for line in commentary.splitlines() if line.strip())
    page = (
        "<!doctype html><html><head><meta charset='utf-8'><title>AP digest " + summary.get("as_of", "") + "</title>"
        "<style>body{font:14px/1.45 system-ui,sans-serif;margin:24px;color:#1c2330}h1{font-size:20px}"
        "table{border-collapse:collapse;width:100%}th,td{border-bottom:1px solid #e3e6ec;padding:6px 8px;text-align:left}"
        "th{background:#f3f5f8;font-size:12px}.od{color:#b42318;font-weight:600}.note{background:#f6f7f9;padding:10px 16px;border-radius:8px}"
        "</style></head><body>"
        "<h1>Accounts payable digest, " + summary.get("as_of", "") + "</h1>"
        + ("<div class='note'><ul>" + bullets + "</ul></div>" if bullets else "")
        + "<table><thead><tr><th>Business</th><th>Bills to review</th><th>Exceptions</th><th>Drafts in Xero</th>"
          "<th>Awaiting approval</th><th>Due by " + summary.get("due_by", "") + "</th><th>Overdue</th><th>Note</th></tr></thead>"
        + "<tbody>" + ("".join(rows) or "<tr><td colspan='8'>No client businesses are set up yet.</td></tr>") + "</tbody></table>"
        "<p style='color:#5d6778'>Amounts are amounts due from Xero. Generated by Bookkeeping for Xero.</p></body></html>"
    )
    saved = api.artifacts.put(title="AP digest " + summary.get("as_of", ""), content=page,
                              file_name="ap-digest-" + summary.get("as_of", "") + ".html", kind="document",
                              mime_type="text/html", tags=["bookkeeping", "ap-digest"])
    artifact_url = (saved or {}).get("url") or ""
    recipients = summary.get("recipients") or []
    if recipients:
        overdue = sum(c["overdue"][0] for c in clients)
        review = sum(c["in_review"] for c in clients)
        api.notify.send(title="Weekly AP digest is ready",
                        body=(str(review) + " bill(s) to review, " + str(overdue) + " overdue. " + artifact_url).strip(),
                        user_ids=recipients)
